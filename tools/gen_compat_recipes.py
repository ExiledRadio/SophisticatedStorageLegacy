"""Writes the recipes of the compat tiers and woods (copper, netherite, crimson, warped).

Usage:
    python -I tools/gen_compat_recipes.py <SophisticatedStorageLegacy dir>

They go to assets/sstoragelegacy/compat_recipes/<folder>/, which MaterialCompat loads in postInit
only when an installed mod adds the material (copper_and_netherite needs both). Shapes follow the
original's generated 1.18 recipes (GPL); tags become ore names. Netherite storages are shapeless
(storage + netherite ingot) as in the 1.20 original, since 1.12 has no smithing table. Copper
goes to the Nether Star tier the way every other tier does here: obsidian and a Nether Star.
Safe to re-run: it rewrites the four folders.
"""
import json
import os
import shutil
import sys

NS = "sstoragelegacy"
HEADER = "Generated by tools/gen_compat_recipes.py from Sophisticated Storage (c) P3pp3rF1y, GPLv3."


def ore(name):
    return {"type": "forge:ore_dict", "ore": name}


def item(name):
    return {"item": name if ":" in name else NS + ":" + name}


def tier_shaped(pattern, key, result):
    return {"type": NS + ":storage_tier_upgrade", "pattern": pattern, "key": key, "result": item(result)}


def main():
    base = os.path.join(sys.argv[1], "src", "main", "resources", "assets", NS, "compat_recipes")
    recipes = {}
    ring = ["CCC", "CSC", "CCC"]
    plus = [" I ", "ISI", " I "]
    # ---- copper ----
    c = recipes.setdefault("copper", {})
    for kind in ("barrel", "chest", "shulker_box"):
        c["copper_" + kind] = tier_shaped(ring, {"C": ore("ingotCopper"), "S": item(kind)}, "copper_" + kind)
        c["iron_%s_from_copper_%s" % (kind, kind)] = tier_shaped(plus, {"I": ore("ingotIron"), "S": item("copper_" + kind)}, "iron_" + kind)
    for n in range(1, 5):
        c["limited_copper_barrel_%d" % n] = tier_shaped(ring, {"C": ore("ingotCopper"), "S": item("limited_barrel_%d" % n)}, "limited_copper_barrel_%d" % n)
        c["limited_iron_barrel_%d_from_limited_copper_barrel_%d" % (n, n)] = tier_shaped(
            plus, {"I": ore("ingotIron"), "S": item("limited_copper_barrel_%d" % n)}, "limited_iron_barrel_%d" % n)
    c["copper_shulker_from_copper_chest"] = tier_shaped(["S", "C", "S"], {"C": item("copper_chest"), "S": item("minecraft:shulker_shell")}, "copper_shulker_box")
    c["basic_to_copper_tier_upgrade"] = {"type": "forge:ore_shaped", "pattern": ring,
                                         "key": {"C": ore("ingotCopper"), "S": item("minecraft:redstone_torch")}, "result": item("basic_to_copper_tier_upgrade")}
    c["copper_to_iron_tier_upgrade"] = {"type": "forge:ore_shaped", "pattern": [" I ", "IRI", " I "],
                                        "key": {"I": ore("ingotIron"), "R": item("minecraft:redstone_torch")}, "result": item("copper_to_iron_tier_upgrade")}
    c["copper_to_gold_tier_upgrade"] = {"type": "forge:ore_shaped", "pattern": ["GGG", "GTG", "GGG"],
                                        "key": {"G": ore("ingotGold"), "T": item("copper_to_iron_tier_upgrade")}, "result": item("copper_to_gold_tier_upgrade")}
    c["copper_to_diamond_tier_upgrade"] = {"type": "forge:ore_shaped", "pattern": ["DDD", "DTD", "DDD"],
                                           "key": {"D": ore("gemDiamond"), "T": item("copper_to_gold_tier_upgrade")}, "result": item("copper_to_diamond_tier_upgrade")}
    c["copper_to_nether_star_tier_upgrade"] = {"type": "forge:ore_shaped", "pattern": ["ONO", "OTO", "OOO"],
                                               "key": {"O": ore("obsidian"), "N": ore("netherStar"), "T": item("copper_to_diamond_tier_upgrade")},
                                               "result": item("copper_to_nether_star_tier_upgrade")}
    # ---- netherite ----
    nr = recipes.setdefault("netherite", {})
    for kind in ("barrel", "chest", "shulker_box"):
        nr["netherite_" + kind] = {"type": NS + ":storage_tier_upgrade_shapeless",
                                   "ingredients": [item("diamond_" + kind), ore("ingotNetherite")], "result": item("netherite_" + kind)}
    for n in range(1, 5):
        nr["limited_netherite_barrel_%d" % n] = {"type": NS + ":storage_tier_upgrade_shapeless",
                                                 "ingredients": [item("limited_diamond_barrel_%d" % n), ore("ingotNetherite")],
                                                 "result": item("limited_netherite_barrel_%d" % n)}
    nr["netherite_shulker_from_netherite_chest"] = tier_shaped(["S", "C", "S"], {"C": item("netherite_chest"), "S": item("minecraft:shulker_shell")}, "netherite_shulker_box")
    for source, upgrade in (("minecraft:redstone_torch", "diamond"), ("basic_to_diamond_tier_upgrade", "basic"),
                            ("iron_to_diamond_tier_upgrade", "iron"), ("gold_to_diamond_tier_upgrade", "gold")):
        nr["%s_to_netherite_tier_upgrade" % upgrade] = {"type": "forge:ore_shapeless", "ingredients": [item(source), ore("ingotNetherite")],
                                                        "result": item("%s_to_netherite_tier_upgrade" % upgrade)}
    both = recipes.setdefault("copper_and_netherite", {})
    both["copper_to_netherite_tier_upgrade"] = {"type": "forge:ore_shapeless", "ingredients": [item("copper_to_diamond_tier_upgrade"), ore("ingotNetherite")],
                                                "result": item("copper_to_netherite_tier_upgrade")}
    # ---- crimson / warped ----
    for wood, cap in (("crimson", "Crimson"), ("warped", "Warped")):
        w = recipes.setdefault(wood, {})
        planks, slab, torch = ore("plank" + cap), ore("slab" + cap), item("minecraft:redstone_torch")
        nbt = {"woodType": wood}
        w[wood + "_barrel"] = {"type": "forge:ore_shaped", "pattern": ["PSP", "PRP", "PSP"], "key": {"P": planks, "S": slab, "R": torch},
                               "result": dict(item("barrel"), nbt=nbt)}
        w[wood + "_chest"] = {"type": "forge:ore_shaped", "pattern": ["PPP", "PRP", "PPP"], "key": {"P": planks, "R": torch},
                              "result": dict(item("chest"), nbt=nbt)}
        limited = {1: ["PSP", "PRP", "PPP"], 2: ["PPP", "SRS", "PPP"], 3: ["PSP", "PRP", "SPS"], 4: ["SPS", "PRP", "SPS"]}
        for n, pattern in limited.items():
            w["%s_limited_barrel_%d" % (wood, n)] = {"type": "forge:ore_shaped", "pattern": pattern, "key": {"P": planks, "S": slab, "R": torch},
                                                     "result": dict(item("limited_barrel_%d" % n), nbt=nbt)}
    count = 0
    for folder, entries in recipes.items():
        path = os.path.join(base, folder)
        if os.path.isdir(path):
            shutil.rmtree(path)
        os.makedirs(path)
        for name, recipe in entries.items():
            recipe = dict(recipe)
            recipe["__comment"] = HEADER
            with open(os.path.join(path, name + ".json"), "w", encoding="utf-8", newline="\n") as fh:
                json.dump(recipe, fh, indent=2)
                fh.write("\n")
            count += 1
    print("wrote", count, "recipes")


if __name__ == "__main__":
    main()
