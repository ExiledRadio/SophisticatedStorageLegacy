"""Builds the part models barrels with materials are drawn from, and their wood defaults.

Usage:
    python -I tools/gen_barrel_material_models.py <SS118Reference dir> <SophisticatedStorageLegacy dir>

The original draws a barrel with materials (other blocks' looks on its parts) from three
"dynamic part" models per barrel kind: the whole barrel, its core (the faces' insides) and its
trim (the one-pixel borders, plus a limited barrel's front rings). Their texture variables are
the material parts (top, side, bottom, top_trim, side_trim, bottom_trim, top_inner_trim); a part
without a material keeps the wood's own texture. This writes those models, with the original's
composite models flattened, to models/block/barrel_part/, and barrel_materials.json listing, for
each kind (barrel, limited_barrel_1..4) and flat or not, the three models and every wood's
textures. BarrelMaterialModel reads that file when models are baked.

Safe to re-run: it overwrites only the files it writes.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_barrel_models as gen  # noqa: E402
import gen_limited_barrel_models as limited_gen  # noqa: E402

KINDS = ["barrel", "limited_barrel_1", "limited_barrel_2", "limited_barrel_3", "limited_barrel_4"]
HEADER = "Generated by tools/gen_barrel_material_models.py from Sophisticated Storage (c) P3pp3rF1y, GPLv3."


def definition(ref_models, name):
    """A barrel kind's model definition with its parent chain merged: dynamic part models and
    the wood base textures (the child's win)."""
    model = gen.load(ref_models, name)
    parts = {}
    woods = {}
    if "parent" in model:
        parent = definition(ref_models, model["parent"].split(":")[-1])
        parts.update(parent["parts"])
        for wood, textures in parent["woods"].items():
            woods[wood] = dict(textures)
    parts.update({k: v for k, v in model.get("dynamic_part_models", {}).items() if k in ("whole", "core", "trim")})
    for wood, overrides in model.get("wood_overrides", {}).items():
        woods.setdefault(wood, {}).update(overrides.get("base", {}).get("textures", {}))
    return {"parts": parts, "woods": woods}


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = dict(data)
    data["__comment"] = HEADER
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, indent=2)
        fh.write("\n")


def main():
    ref, mod = sys.argv[1], sys.argv[2]
    ref_models = os.path.join(ref, "src", "main", "resources", "assets", gen.OLD_NS, "models")
    assets = os.path.join(mod, "src", "main", "resources", "assets", gen.NEW_NS)
    written = {}
    descriptor = {}
    for kind in KINDS:
        descriptor[kind] = {}
        for flat in (False, True):
            name = ("block/flat/" if flat else "block/") + kind
            d = definition(ref_models, name)
            if flat and kind != "barrel" and not all(k in d["parts"] for k in ("whole", "core", "trim")):
                # A flat limited barrel without its own parts uses the flat barrel's.
                fallback = definition(ref_models, "block/flat/barrel")["parts"]
                for key, value in fallback.items():
                    d["parts"].setdefault(key, value)
            entry = {}
            for key in ("whole", "core", "trim"):
                source = d["parts"][key]
                if source == "minecraft:block/cube_bottom_top":
                    out_name = "flat_whole"
                    if out_name not in written:
                        written[out_name] = gen.cube_bottom_top({})
                else:
                    out_name = source.split(":")[-1].split("/")[-1]
                    if out_name not in written:
                        model = limited_gen.load_resolved(ref_models, source.split(":")[-1])
                        written[out_name] = gen.port_part(model)
                entry[key] = "%s:block/barrel_part/%s" % (gen.NEW_NS, out_name)
            entry["woods"] = {wood: {k: gen.ns(v) for k, v in textures.items()} for wood, textures in sorted(d["woods"].items()) if wood in gen.WOODS}
            descriptor[kind]["flat" if flat else "normal"] = entry
    for out_name, model in written.items():
        model = dict(model)
        model.pop("parent", None)
        model.pop("loader", None)
        model["textures"] = {k: gen.ns(v) for k, v in model.get("textures", {}).items()}
        write(os.path.join(assets, "models", "block", "barrel_part", out_name + ".json"), model)
    write(os.path.join(assets, "barrel_materials.json"), descriptor)
    print("part models:", sorted(written))


if __name__ == "__main__":
    main()
