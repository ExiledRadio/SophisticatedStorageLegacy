"""Builds the 1.12 barrel block and item models from the 1.18.x reference's barrel parts.

Usage (Windows paths):
    python -I tools/gen_barrel_models.py <SS118Reference dir> <SophisticatedStorageLegacy dir>

The original renders barrels through a custom model loader that stacks three parts:
the wood barrel (unless both colours are dyed), the tinted accent overlay (if the trim is
dyed) and the tinted main overlay (if the body is dyed). 1.12 can do the same with a
vanilla multipart blockstate, driven by the actual-state properties the block reads from
its tile entity:

    facing, open           saved in metadata
    flat_top, wood, tint   from the tile (tint = none / main / accent / both)

Items can't use multipart, so every item variant gets one merged model instead.

Higher tiers (iron, gold, diamond, nether star) are separate blocks with the same parts plus the
original's "tier" part on top: metal corners on every face. The wood tier's corners are fully
transparent in the original, so the wood barrel leaves that part out. Each tier gets its own
blockstate (<tier>_barrel.json) and item models (barrel/<tier>_<key>). The nether star textures
come from tools/make_nether_star_barrel.py (netherite doesn't exist in 1.12).

Tint indexes: the original uses 1000 (main) and 1001 (accent); we use 0 and 1.
Safe to re-run: it overwrites only the files it writes.
"""
import copy
import json
import os
import sys

OLD_NS = "sophisticatedstorage"
NEW_NS = "sstoragelegacy"

WOODS = ("oak", "spruce", "birch", "jungle", "acacia", "dark_oak", "crimson", "warped")
TINTS = ("none", "main", "accent", "both")
TINT_INDEX = {1000: 0, 1001: 1}
# Tiers above wood, with the texture prefix of their corner overlay ("sophisticatedstorage:" is
# rewritten to our namespace, where the nether star textures live).
TIERS = ("copper", "iron", "gold", "diamond", "netherite", "nether_star")

# facing -> (x, y), from the reference blockstate.
ROTATIONS = {
    "down": (180, 180),
    "up": (0, 180),
    "north": (270, 180),
    "south": (270, 0),
    "west": (270, 90),
    "east": (270, 270),
}

HEADER = "Generated by tools/gen_barrel_models.py from Sophisticated Storage (c) P3pp3rF1y, GPLv3."


def ns(value):
    return value.replace(OLD_NS + ":", NEW_NS + ":") if isinstance(value, str) else value


def load(ref_models, name):
    with open(os.path.join(ref_models, name + ".json"), encoding="utf-8") as fh:
        return json.load(fh)


def port_part(model):
    """Namespace and tint-index conversion of one part model with elements."""
    model = copy.deepcopy(model)
    model.pop("credit", None)
    model["textures"] = {k: ns(v) for k, v in model.get("textures", {}).items()}
    for element in model.get("elements", []):
        for face in element["faces"].values():
            if "tintindex" in face:
                face["tintindex"] = TINT_INDEX[face["tintindex"]]
    return model


def resolve_textures(textures):
    """Follow #references until every variable names a real texture."""
    out = dict(textures)
    for _ in range(8):
        changed = False
        for k, v in out.items():
            if v.startswith("#") and v[1:] in out and out[v[1:]] != v:
                out[k] = out[v[1:]]
                changed = True
        if not changed:
            break
    return out


def with_textures(model, overrides):
    model = copy.deepcopy(model)
    textures = dict(model.get("textures", {}))
    textures.update({k: ns(v) for k, v in overrides.items()})
    model["textures"] = resolve_textures(textures)
    return model


def merge(models):
    """Stack several part models into one, prefixing texture variables so they can't clash."""
    merged = {"parent": "block/block", "textures": {}, "elements": []}
    for i, model in enumerate(models):
        prefix = "p%d_" % i
        for k, v in model["textures"].items():
            merged["textures"][prefix + k] = (("#" + prefix + v[1:]) if v.startswith("#") else v)
        for element in model["elements"]:
            element = copy.deepcopy(element)
            for face in element["faces"].values():
                face["texture"] = "#" + prefix + face["texture"][1:]
            merged["elements"].append(element)
    first = models[0]["textures"]
    merged["textures"]["particle"] = first.get("particle", first.get("side"))
    return merged


def cube_bottom_top(textures):
    """The flat-top wood barrel is a plain cube_bottom_top; spelled out so it can be merged."""
    faces = {
        "down": {"uv": [0, 0, 16, 16], "texture": "#bottom", "cullface": "down"},
        "up": {"uv": [0, 0, 16, 16], "texture": "#top", "cullface": "up"},
        "north": {"uv": [0, 0, 16, 16], "texture": "#side", "cullface": "north"},
        "south": {"uv": [0, 0, 16, 16], "texture": "#side", "cullface": "south"},
        "west": {"uv": [0, 0, 16, 16], "texture": "#side", "cullface": "west"},
        "east": {"uv": [0, 0, 16, 16], "texture": "#side", "cullface": "east"},
    }
    return {"textures": dict(textures), "elements": [{"from": [0, 0, 0], "to": [16, 16, 16], "faces": faces}]}


class Parts:
    """Every part model, as {name: model}, built from the reference's barrel.json / flat/barrel.json."""

    def __init__(self, ref_models):
        self.models = {}
        for flat in (False, True):
            suffix = "_flat" if flat else ""
            loader = load(ref_models, "block/flat/barrel" if flat else "block/barrel")
            parts = loader["model_parts"]

            def part(key, extra=None):
                spec = parts[key]
                source = spec["model"].split(":")[1]
                textures = dict(spec.get("textures", {}))
                if extra:
                    textures.update(extra)
                if source == "block/cube_bottom_top":
                    return with_textures(cube_bottom_top({}), textures)
                return with_textures(port_part(load(ref_models, source)), textures)

            for wood in WOODS:
                overrides = loader["wood_overrides"][wood]
                self.models["wood_%s%s" % (wood, suffix)] = part("base", overrides["base"]["textures"])
                self.models["wood_%s_open%s" % (wood, suffix)] = part("base_open", overrides["base_open"]["textures"])
            self.models["tintable_main" + suffix] = part("tintable_main")
            self.models["tintable_main_open" + suffix] = part("tintable_main_open")
            self.models["tintable_accent" + suffix] = part("tintable_accent")
            # Packing tape strips over everything (the original's "packed" part).
            self.models["packed" + suffix] = part("packed")
            # The original's lock icon on a locked barrel's front.
            self.models["locked" + suffix] = part("locked")
            for tier in TIERS:
                textures = {face: "%s:block/%s_barrel_%s" % (OLD_NS, tier, face) for face in ("top", "side", "bottom")}
                textures["top_trim"] = textures["top"]
                textures["particle"] = textures["side"]
                self.models["tier_%s%s" % (tier, suffix)] = part("tier", textures)

    def stack(self, wood, tint, open_, flat, tier=None):
        """The original's layer order: wood base, then accent, then main, then the tier corners."""
        o = "_open" if open_ else ""
        f = "_flat" if flat else ""
        layers = []
        if tint != "both":
            layers.append(self.models["wood_%s%s%s" % (wood, o, f)])
        if tint in ("accent", "both"):
            layers.append(self.models["tintable_accent" + f])
        if tint in ("main", "both"):
            layers.append(self.models["tintable_main%s%s" % (o, f)])
        if tier:
            layers.append(self.models["tier_%s%s" % (tier, f)])
        return layers


def item_key(wood, tint, flat):
    base = "tinted" if tint == "both" else wood + ("" if tint == "none" else "_" + tint)
    return base + ("_flat" if flat else "")


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = dict(data)
    data["__comment"] = HEADER
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, indent=2)
        fh.write("\n")


def barrel_multipart(tier=None):
    multipart = []
    for facing, (x, y) in ROTATIONS.items():
        for flat in (False, True):
            f = "_flat" if flat else ""
            flat_value = "true" if flat else "false"
            for open_ in (False, True):
                o = "_open" if open_ else ""
                open_value = "true" if open_ else "false"
                for wood in WOODS:
                    multipart.append({
                        "when": {"facing": facing, "flat_top": flat_value, "open": open_value,
                                 "wood": wood, "tint": "none|main|accent"},
                        "apply": {"model": "%s:barrel/wood_%s%s%s" % (NEW_NS, wood, o, f), "x": x, "y": y},
                    })
                multipart.append({
                    "when": {"facing": facing, "flat_top": flat_value, "open": open_value, "tint": "main|both"},
                    "apply": {"model": "%s:barrel/tintable_main%s%s" % (NEW_NS, o, f), "x": x, "y": y},
                })
            multipart.append({
                "when": {"facing": facing, "flat_top": flat_value, "tint": "accent|both"},
                "apply": {"model": "%s:barrel/tintable_accent%s" % (NEW_NS, f), "x": x, "y": y},
            })
            if tier:
                multipart.append({
                    "when": {"facing": facing, "flat_top": flat_value, "show_tier": "true"},
                    "apply": {"model": "%s:barrel/tier_%s%s" % (NEW_NS, tier, f), "x": x, "y": y},
                })
            multipart.append({
                "when": {"facing": facing, "flat_top": flat_value, "packed": "true"},
                "apply": {"model": "%s:barrel/packed%s" % (NEW_NS, f), "x": x, "y": y},
            })
            multipart.append({
                "when": {"facing": facing, "flat_top": flat_value, "locked": "true"},
                "apply": {"model": "%s:barrel/locked%s" % (NEW_NS, f), "x": x, "y": y},
            })
    return multipart


def main():
    ref, mod = sys.argv[1], sys.argv[2]
    ref_models = os.path.join(ref, "src", "main", "resources", "assets", OLD_NS, "models")
    assets = os.path.join(mod, "src", "main", "resources", "assets", NEW_NS)
    parts = Parts(ref_models)

    # Block part models.
    for name, model in parts.models.items():
        write(os.path.join(assets, "models", "block", "barrel", name + ".json"), model)

    # Multipart blockstates: the wood barrel, then each tier with its corners on top.
    multipart = barrel_multipart()
    write(os.path.join(assets, "blockstates", "barrel.json"), {"multipart": multipart})
    for tier in TIERS:
        write(os.path.join(assets, "blockstates", tier + "_barrel.json"), {"multipart": barrel_multipart(tier)})

    # Item models: one merged model per look, per tier.
    keys = set()
    for flat in (False, True):
        for tint in TINTS:
            for wood in WOODS:
                key = item_key(wood, tint, flat)
                if key in keys:
                    continue
                keys.add(key)
                write(os.path.join(assets, "models", "item", "barrel", key + ".json"),
                      merge(parts.stack(wood, tint, False, flat)))
                for tier in TIERS:
                    write(os.path.join(assets, "models", "item", "barrel", tier + "_" + key + ".json"),
                          merge(parts.stack(wood, tint, False, flat, tier)))

    print("part models:", len(parts.models))
    print("multipart entries:", len(multipart))
    print("item models:", len(keys) * (1 + len(TIERS)))


if __name__ == "__main__":
    main()
